"""Общие исключения адаптеров приёма пакета по облачной ссылке.

Правило изоляции рисков: сбой ОДНОГО адаптера (особенно Облака Mail.ru —
у него нет официального API) никогда не должен приводить к исключению,
которое обрушивает приём пакета целиком. Вызывающий код (bot/service)
ловит IngestError и опускается до "пришлите файлы напрямую"."""


class IngestError(Exception):
    """Базовая ошибка приёма файла/папки по публичной ссылке."""


class UnsupportedLinkError(IngestError):
    """Ссылка не похожа на публичную ссылку этого облака."""


class RemoteNotFoundError(IngestError):
    """Облако ответило, что ресурс не найден или ссылка не публична."""


class RemoteUnavailableError(IngestError):
    """Сеть/облако недоступны, таймаут, или облако изменило формат ответа
    (актуально для Mail.ru — там нет официального контракта API)."""
